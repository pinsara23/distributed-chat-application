"""Wire format for E2EE chat messages.

The server only ever sees opaque ciphertext. Plaintext is never accepted:
``WsMessageIn`` forbids unknown fields, so a stray ``content`` field is rejected.
"""

import base64
import binascii
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator

NONCE_BYTES = 12            # AES-GCM nonce
TAG_BYTES = 16              # AES-GCM authentication tag (appended to ciphertext)
MAX_CIPHERTEXT_BYTES = 32 * 1024


def _b64(value: str, field: str) -> bytes:
    try:
        return base64.b64decode(value, validate=True)
    except (binascii.Error, ValueError):
        raise ValueError(f"{field} must be valid base64")


class WsMessageIn(BaseModel):
    """A message sent by a client over the WebSocket."""

    model_config = ConfigDict(extra="forbid")

    # Generated by the sender; bound into the AES-GCM AAD and used as the
    # idempotency key, so resending after a reconnect cannot create duplicates.
    message_id: UUID
    conversation_id: int
    target_user_id: int
    ciphertext: str = Field(max_length=MAX_CIPHERTEXT_BYTES * 2)
    nonce: str = Field(max_length=64)
    key_version: int = Field(default=1, ge=1)            # sender's key version
    recipient_key_version: int | None = Field(default=None, ge=1)

    @field_validator("ciphertext")
    @classmethod
    def _check_ciphertext(cls, value: str) -> str:
        raw = _b64(value, "ciphertext")
        if not TAG_BYTES <= len(raw) <= MAX_CIPHERTEXT_BYTES:
            raise ValueError("ciphertext has an invalid length")
        return value

    @field_validator("nonce")
    @classmethod
    def _check_nonce(cls, value: str) -> str:
        if len(_b64(value, "nonce")) != NONCE_BYTES:
            raise ValueError(f"nonce must be {NONCE_BYTES} bytes")
        return value

    @property
    def ciphertext_bytes(self) -> bytes:
        return base64.b64decode(self.ciphertext)

    @property
    def nonce_bytes(self) -> bytes:
        return base64.b64decode(self.nonce)


def serialize_message(message) -> dict:
    """Serialize a persisted message for REST history and real-time events."""
    created_at = getattr(message, "created_at", None)
    return {
        "id": message.id,
        "message_uuid": str(message.message_uuid),
        "conversation_id": message.conversation_id,
        "sender_id": message.sender_id,
        "ciphertext": base64.b64encode(bytes(message.ciphertext)).decode("ascii"),
        "nonce": base64.b64encode(bytes(message.nonce)).decode("ascii"),
        "key_version": message.key_version,
        "recipient_key_version": getattr(message, "recipient_key_version", None),
        "created_at": created_at.isoformat() if created_at else None,
    }
